/** Minimal HCL parser – extracts resource blocks from .tf file content */
export interface ParsedTfResource {
  type: string;      // e.g. "cloudflare_record"
  label: string;     // e.g. "dns_abc123_0"
  body: string;      // raw HCL body between { }
}

/**
 * Parse resource blocks from HCL text.
 * This is a best-effort parser for the HCL subset we generate.
 */
export function parseTerraformResources(hcl: string): ParsedTfResource[] {
  const resources: ParsedTfResource[] = [];
  const regex = /resource\s+"([^"]+)"\s+"([^"]+)"\s*\{/g;
  let match: RegExpExecArray | null;

  while ((match = regex.exec(hcl)) !== null) {
    const type = match[1];
    const label = match[2];
    const startIdx = match.index + match[0].length;

    // Find matching closing brace (handle nested braces)
    let depth = 1;
    let i = startIdx;
    while (i < hcl.length && depth > 0) {
      if (hcl[i] === '{') depth++;
      else if (hcl[i] === '}') depth--;
      i++;
    }

    const body = hcl.slice(startIdx, i - 1).trim();
    resources.push({ type, label, body });
  }

  return resources;
}

/** Extract simple key=value attributes from an HCL block body (top-level only) */
export function extractAttributes(body: string): Record<string, string> {
  const attrs: Record<string, string> = {};
  // Match lines like:  key = "value"  or  key = value  or  key = true
  const lines = body.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    const m = trimmed.match(/^([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(.+)$/);
    if (m) {
      const key = m[1];
      let val = m[2].trim();
      // Strip quotes from string values
      if (val.startsWith('"') && val.endsWith('"')) {
        val = val.slice(1, -1);
      }
      attrs[key] = val;
    }
  }
  return attrs;
}
