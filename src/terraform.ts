function poolToTf(p: CFPool, idx: number): string {
  const origins = p.origins.map(o => ({
    name: o.name,
    address: o.address,
    enabled: o.enabled,
    weight: o.weight,
    ...(o.header ? { header: o.header } : {}),
  }));

  const attrs: Record<string, unknown> = {
    account_id: hclExpr('var.account_id'),
    name: p.name,
    description: p.description,
    enabled: p.enabled,
    minimum_origins: p.minimum_origins,
    origins,
  };
  if (p.notification_email) attrs.notification_email = p.notification_email;
  // monitor is an ID reference – in a real config this would use a resource reference
  if (p.monitor) attrs.monitor = p.monitor;

  return resourceBlock('cloudflare_load_balancer_pool', resourceLabel('pool', p.id, idx), attrs);
}

function loadBalancerToTf(lb: CFLoadBalancer, idx: number): string {
  const attrs: Record<string, unknown> = {
    zone_id: hclExpr('var.zone_id'),
    name: lb.name,
    description: lb.description || '',
    default_pools: lb.default_pools,
    fallback_pool: lb.fallback_pool,
    proxied: lb.proxied,
    ttl: lb.ttl,
    steering_policy: lb.steering_policy,
    session_affinity: lb.session_affinity,
    session_affinity_ttl: lb.session_affinity_ttl,
  };
  if (lb.rules && lb.rules.length > 0) {
    attrs.rules = lb.rules.map(r => ({
      name: r.name,
      condition: r.condition,
      disabled: r.disabled,
      priority: r.priority,
      terminates: r.terminates,
      ...(r.fixed_response ? { fixed_response: r.fixed_response } : {}),
      ...(r.overrides ? { overrides: r.overrides } : {}),
    }));
  }

  return resourceBlock('cloudflare_load_balancer', resourceLabel('lb', lb.id, idx), attrs);
}

