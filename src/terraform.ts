type HclExpr = { __hclExpr: string };
function hclExpr(expr: string): HclExpr {
  return { __hclExpr: expr };
}

/** Escape a string for HCL – double-quotes and backslashes */
function hclString(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
}

/** Produce a safe Terraform resource label from an arbitrary id */
function resourceLabel(prefix: string, id: string, index: number): string {
  const sanitized = id.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 40);
  return `${prefix}_${sanitized}_${index}`;
}

/** Indent every line of a string by `n` spaces */
function indent(s: string, n: number): string {
  const pad = ' '.repeat(n);
  return s.split('\n').map(l => pad + l).join('\n');
}

/** Render a value as HCL – handles strings, numbers, booleans, arrays, objects */
function hclValue(value: unknown, depth = 0): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return `"${hclString(value)}"`;

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map(v => hclValue(v, depth + 1));
    // Simple arrays on one line if short
    const oneLine = `[${items.join(', ')}]`;
    if (oneLine.length < 80 && !oneLine.includes('\n')) return oneLine;
    return '[\n' + items.map(i => indent(i + ',', (depth + 1) * 2)).join('\n') + '\n' + ' '.repeat(depth * 2) + ']';
  }

  if (typeof value === 'object') {
    // Raw HCL expression
    if ((value as any).__hclExpr && typeof (value as any).__hclExpr === 'string') {
      return (value as any).__hclExpr;
    }
    const obj = value as Record<string, unknown>;
    const keys = Object.keys(obj);
    if (keys.length === 0) return '{}';
    const lines = keys.map(k => {
      const safeKey = /^[a-zA-Z_][a-zA-Z0-9_-]*$/.test(k) ? k : `"${hclString(k)}"`;
      return `${safeKey} = ${hclValue(obj[k], depth + 1)}`;
    });
    const oneLine = `{ ${lines.join(', ')} }`;
    if (oneLine.length < 80 && !oneLine.includes('\n')) return oneLine;
    return '{\n' + lines.map(l => indent(l, (depth + 1) * 2)).join('\n') + '\n' + ' '.repeat(depth * 2) + '}';
  }

  return `"${String(value)}"`;
}

/** Build a complete resource block */
function resourceBlock(type: string, label: string, attrs: Record<string, unknown>): string {
  const lines: string[] = [`resource "${type}" "${label}" {`];
  for (const [key, val] of Object.entries(attrs)) {
    if (val === undefined || val === null) continue;
    lines.push(`  ${key} = ${hclValue(val, 1)}`);
  }
  lines.push('}');
  return lines.join('\n');
}

