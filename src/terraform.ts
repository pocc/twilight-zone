/** Generate all Terraform files from a ZoneExport */
export function generateTerraformFiles(data: ZoneExport): TerraformFile[] {
  const zoneId = data.zone.id;
  const accountId = data.zone.account.id;
  const zoneName = data.zone.name;

  const files: TerraformFile[] = [
    generateMainTf(zoneId, accountId, zoneName),
  ];

  const optional: (TerraformFile | null)[] = [
    generateDnsTf(data.dnsRecords),
    generateSettingsTf(data.settings),
    generatePageRulesTf(data.pageRules),
    generateRulesetsTf(data.rulesets),
    generateWorkersTf(
      data.workers,
      data.workerRoutes,
      (data.workerCustomDomains || []).filter(cd => cd.zone_id === data.zone.id)
    ),
    generateLoadBalancersTf(data.loadBalancers, data.pools, data.monitors),
    generateSecurityTf(data.firewallRules, data.rateLimits, data.accessApps, data.accessPolicies),
    generateExtraTf(
      data.spectrumApps, data.customCertificates, data.customHostnames,
      data.emailRoutingRules, data.waitingRooms, data.turnstileWidgets
    ),
    generateStorageTf(data.kvNamespaces, data.r2Buckets, data.d1Databases, data.queues),
  ];

  for (const f of optional) {
    if (f) files.push(f);
  }

  return files;
}

/** Generate a single concatenated .tf file (for simple download) */
export function generateTerraformBundle(data: ZoneExport): string {
  return generateTerraformFiles(data)
    .map(f => `# ═══ ${f.filename} ${'═'.repeat(Math.max(0, 60 - f.filename.length))}\n\n${f.content}`)
    .join('\n\n');
}

/** Generate a summary of what would be generated */
export function terraformExportSummary(data: ZoneExport): {
  files: { filename: string; resourceCount: number }[];
  totalResources: number;
} {
  const customRulesets = data.rulesets.filter(rs => !isManagedRuleset(rs));
  const editableSettings = data.settings.filter(
    s => s.editable && !READ_ONLY_SETTINGS.has(s.id) && !BLOCKED_SETTINGS.has(s.id) && !isNoOpSetting(s)
  );
  const tfWorkersCount = data.workers.filter(w => (w as any).isAccountLevel !== true && Boolean((w as any).script)).length;

  const counts: { filename: string; resourceCount: number }[] = [
    { filename: 'main.tf', resourceCount: 1 },
  ];

  if (data.dnsRecords.length > 0) counts.push({ filename: 'dns.tf', resourceCount: data.dnsRecords.length });
  if (editableSettings.length > 0) counts.push({ filename: 'settings.tf', resourceCount: editableSettings.length });
  if (data.pageRules.length > 0) counts.push({ filename: 'page_rules.tf', resourceCount: data.pageRules.length });
  if (customRulesets.length > 0) counts.push({ filename: 'rulesets.tf', resourceCount: customRulesets.length });
  const wcdCount = (data.workerCustomDomains || []).filter(cd => cd.zone_id === data.zone.id).length;
  if (tfWorkersCount > 0 || data.workerRoutes.length > 0 || wcdCount > 0) {
    counts.push({ filename: 'workers.tf', resourceCount: tfWorkersCount + data.workerRoutes.length + wcdCount });
  }
  if (data.loadBalancers.length + data.pools.length + data.monitors.length > 0) {
    counts.push({ filename: 'load_balancers.tf', resourceCount: data.loadBalancers.length + data.pools.length + data.monitors.length });
  }
  const secCount = data.firewallRules.length + data.rateLimits.length + data.accessApps.length + data.accessPolicies.length;
  if (secCount > 0) counts.push({ filename: 'security.tf', resourceCount: secCount });
  const extraCount = data.spectrumApps.length + data.customCertificates.length + data.customHostnames.length +
    data.emailRoutingRules.length + data.waitingRooms.length + data.turnstileWidgets.length;
  if (extraCount > 0) counts.push({ filename: 'extra.tf', resourceCount: extraCount });
  const storageCount = data.kvNamespaces.length + data.r2Buckets.length + data.d1Databases.length + data.queues.length;
  if (storageCount > 0) counts.push({ filename: 'storage.tf', resourceCount: storageCount });

  return {
    files: counts,
    totalResources: counts.reduce((s, c) => s + c.resourceCount, 0),
  };
}

