function generateProvider(zoneId: string, accountId: string): string {
  return [
    '# ──────────────────────────────────────────────────────────────────',
    '# Terraform configuration generated by Twilight Zone',
    '# https://github.com/cloudflare/cf-terraforming (resource reference)',
    '# ──────────────────────────────────────────────────────────────────',
    '',
    'terraform {',
    '  required_providers {',
    '    cloudflare = {',
    '      source  = "cloudflare/cloudflare"',
    '      version = "= 5.17.0"',
    '    }',
    '  }',
    '}',
    '',
    'provider "cloudflare" {',
    '  api_token = var.cloudflare_api_token',
    '}',
    '',
    'variable "cloudflare_api_token" {',
    '  type      = string',
    '  sensitive = true',
    '}',
    '',
    `variable "zone_id" {`,
    `  default = "${zoneId}"`,
    '}',
    '',
    `variable "account_id" {`,
    `  default = "${accountId}"`,
    '}',
    '',
  ].join('\n');
}

// ── DNS Records ──────────────────────────────────────────────────────

function dnsRecordToTf(r: CFDNSRecord, idx: number): string {
  const attrs: Record<string, unknown> = {
    zone_id: hclExpr('var.zone_id'),
    name: r.name,
    type: r.type,
    ttl: r.ttl,
    proxied: r.proxied ?? false,
  };

  // Records with `data` blocks (CAA, SRV, HTTPS, etc.) omit `content`
  if (r.data && Object.keys(r.data).length > 0) {
    attrs.data = r.data;
  } else {
    attrs.content = r.content;
  }

  if (r.priority !== undefined) {
    attrs.priority = r.priority;
  }

  if (r.comment) attrs.comment = r.comment;
  if (r.tags && r.tags.length > 0) attrs.tags = r.tags;
  if (r.settings && Object.keys(r.settings).length > 0) attrs.settings = r.settings;

  return resourceBlock('cloudflare_dns_record', resourceLabel('dns', r.id, idx), attrs);
}

// ── Zone Settings ────────────────────────────────────────────────────

function zoneSettingsToTf(settings: CFZoneSetting[]): string {
  const editable = settings.filter(
    s => s.editable && !READ_ONLY_SETTINGS.has(s.id) && !BLOCKED_SETTINGS.has(s.id) && !isNoOpSetting(s)
  );
  if (editable.length === 0) return '';

  const blocks: string[] = [];
  for (let i = 0; i < editable.length; i++) {
    const s = editable[i];
    const attrs: Record<string, unknown> = {
      zone_id: hclExpr('var.zone_id'),
      setting_id: s.id,
    };
    if (s.id === 'ssl_recommender') {
      // Special case per provider docs: uses `enabled` instead of `value`.
      attrs.enabled = Boolean(s.value);
    } else {
      attrs.value = s.value;
    }
    blocks.push(resourceBlock('cloudflare_zone_setting', resourceLabel('setting', s.id, i), attrs));
  }

  return blocks.join('\n\n');
}

// ── Page Rules ───────────────────────────────────────────────────────

function pageRuleToTf(rule: CFPageRule, idx: number): string {
  const target = rule.targets?.[0]?.constraint?.value || '*';

  // Flatten actions: {id: "ssl", value: "full"} → {ssl: "full"}
  const actionMap: Record<string, unknown> = {};
  for (const a of rule.actions) {
    actionMap[a.id] = a.value ?? true;
  }

  const attrs: Record<string, unknown> = {
    zone_id: hclExpr('var.zone_id'),
    target,
    priority: rule.priority,
    status: rule.status,
    actions: actionMap,
  };

  return resourceBlock('cloudflare_page_rule', resourceLabel('pagerule', rule.id, idx), attrs);
}

// ── Rulesets ─────────────────────────────────────────────────────────

function rulesetRuleToObj(rule: CFRulesetRule): Record<string, unknown> {
  const obj: Record<string, unknown> = {
    action: rule.action,
    expression: rule.expression,
    enabled: rule.enabled ?? true,
  };
  if (rule.description) obj.description = rule.description;
  if (rule.action_parameters && Object.keys(rule.action_parameters).length > 0) {
    obj.action_parameters = rule.action_parameters;
  }
  return obj;
}

function rulesetToTf(rs: CFRuleset, idx: number): string {
  const rules = (rs.rules || []).map(rulesetRuleToObj);
  const attrs: Record<string, unknown> = {
    zone_id: hclExpr('var.zone_id'),
    name: rs.name || 'default',
    description: rs.description || '',
    kind: rs.kind || 'zone',
    phase: rs.phase,
    rules,
  };

  return resourceBlock('cloudflare_ruleset', resourceLabel('ruleset', rs.id, idx), attrs);
}

// ── Workers ──────────────────────────────────────────────────────────

function escapeTerraformTemplateLiterals(s: string): string {
  // Prevent `${...}` / `%{...}` sequences inside heredocs from being interpreted by Terraform.
  return s.replace(/\$\{/g, '$${').replace(/%\{/g, '%%{');
}

function workerBindingToTfV5(b: CFWorkerBinding): Record<string, unknown> | null {
  const base: Record<string, unknown> = { name: b.name, type: b.type };
  switch (b.type) {
    case 'plain_text':
      if (b.text !== undefined) base.text = b.text;
      return base;
    case 'secret_text':
      base.text = 'REPLACE_ME';
      return base;
    case 'kv_namespace':
      if (b.namespace_id) base.namespace_id = b.namespace_id;
      return base;
    case 'r2_bucket':
      if (b.bucket_name) base.bucket_name = b.bucket_name;
      return base;
    case 'd1':
      // Provider expects `id` for the D1 database ID.
      if (b.database_id) base.id = b.database_id;
      return base;
    case 'queue':
      if (b.queue_name) base.queue_name = b.queue_name;
      return base;
    case 'durable_object_namespace':
      if (b.class_name) base.class_name = b.class_name;
      if (b.script_name) base.script_name = b.script_name;
      return base;
    case 'service':
      if (b.service) base.service = b.service;
      if (b.environment) base.environment = b.environment;
      return base;
    default:
      // Unknown binding types are skipped to avoid emitting invalid schemas.
      return null;
  }
}

function workerToTf(w: CFWorkerScript, idx: number): string {
  const attrs: Record<string, unknown> = {
    account_id: hclExpr('var.account_id'),
    script_name: w.id,
  };

  if (w.script) {
    attrs.content = hclExpr(`<<-EOT\n${escapeTerraformTemplateLiterals(w.script)}\nEOT`);
  }

  if (w.script_format === 'modules' && w.main_module) {
    attrs.main_module = w.main_module;
  }

  if (w.bindings && w.bindings.length > 0) {
    const bindings = w.bindings
      .map(workerBindingToTfV5)
      .filter(Boolean) as Record<string, unknown>[];
    if (bindings.length > 0) {
      attrs.bindings = bindings;
    }
  }

  return resourceBlock('cloudflare_workers_script', resourceLabel('worker', w.id, idx), attrs);
}

