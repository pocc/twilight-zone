function generateSecurityTf(
  firewallRules: CFFirewallRule[],
  rateLimits: CFRateLimit[],
  accessApps: CFAccessApp[],
  accessPolicies: CFAccessPolicy[]
): TerraformFile | null {
  if (firewallRules.length === 0 && rateLimits.length === 0 && accessApps.length === 0) return null;
  const parts: string[] = [
    '# Security – Firewall Rules, Rate Limits, Access Applications',
    '',
  ];
  for (let i = 0; i < firewallRules.length; i++) {
    parts.push(firewallRuleToTf(firewallRules[i], i));
    parts.push('');
  }
  for (let i = 0; i < rateLimits.length; i++) {
    parts.push(rateLimitToTf(rateLimits[i], i));
    parts.push('');
  }

  // Zero Trust Access Policies (account-level) must exist before applications can reference them.
  const policyLabelByCompositeId = new Map<string, string>();
  if (accessPolicies.length > 0) {
    parts.push('# Zero Trust Access Policies');
    parts.push('');
    for (let pi = 0; pi < accessPolicies.length; pi++) {
      const p = accessPolicies[pi];
      const label = resourceLabel('access_policy', p.id, pi);
      policyLabelByCompositeId.set(p.id, label);
      parts.push(accessPolicyToTf(p, pi));
      parts.push('');
    }
  }

  if (accessApps.length > 0) {
    parts.push('# Zero Trust Access Applications');
    parts.push('');
    for (let i = 0; i < accessApps.length; i++) {
      const app = accessApps[i];
      const refs = accessPolicies
        .filter(p => parseAccessPolicyCompositeId(p.id).appId === app.id)
        .map(p => ({ policyLabel: policyLabelByCompositeId.get(p.id) || resourceLabel('access_policy', p.id, 0), precedence: p.precedence }))
        .sort((a, b) => a.precedence - b.precedence);
      parts.push(accessAppToTf(app, i, refs));
      parts.push('');
    }
  }
  return { filename: 'security.tf', content: parts.join('\n') };
}

