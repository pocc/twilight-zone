// ── Access Applications & Policies ───────────────────────────────────

function parseAccessPolicyCompositeId(id: string): { appId: string | null; policyId: string } {
  const parts = (id || '').split('/');
  if (parts.length >= 2) return { appId: parts[0] || null, policyId: parts.slice(1).join('/') };
  return { appId: null, policyId: id };
}

function accessPolicyToTf(policy: CFAccessPolicy, idx: number): string {
  const attrs: Record<string, unknown> = {
    account_id: hclExpr('var.account_id'),
    decision: policy.decision,
    name: policy.name,
  };
  if (policy.include && policy.include.length > 0) attrs.include = policy.include;
  if (policy.exclude && policy.exclude.length > 0) attrs.exclude = policy.exclude;
  if (policy.require && policy.require.length > 0) attrs.require = policy.require;
  return resourceBlock('cloudflare_zero_trust_access_policy', resourceLabel('access_policy', policy.id, idx), attrs);
}

function accessAppToTf(
  app: CFAccessApp,
  idx: number,
  policyRefs: Array<{ policyLabel: string; precedence: number }>,
): string {
  const attrs: Record<string, unknown> = {
    account_id: hclExpr('var.account_id'),
    name: app.name,
    domain: app.domain,
    type: app.type,
    session_duration: app.session_duration,
    allowed_idps: app.allowed_idps,
    auto_redirect_to_identity: app.auto_redirect_to_identity,
  };

  if (policyRefs.length > 0) {
    attrs.policies = policyRefs.map(p => ({
      id: hclExpr(`cloudflare_zero_trust_access_policy.${p.policyLabel}.id`),
      precedence: p.precedence,
    }));
  }

  return resourceBlock('cloudflare_zero_trust_access_application', resourceLabel('access_app', app.id, idx), attrs);
}

