#!/usr/bin/env node
/**
 * Extract the cloudflare-typescript SDK resource tree into a flat index of
 *   { sdk_path, method, http_method, url_template }
 *
 * Used by scripts/coverage-report.mjs to cross-check the OpenAPI inventory.
 * An endpoint that exists in the OpenAPI spec but NOT in the SDK is usually
 * internal/deprecated and should not penalize migration coverage.
 *
 * Output: coverage/sdk-index.generated.json (gitignored)
 *
 * No network calls — purely static analysis of node_modules/cloudflare/resources.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SDK_ROOT = path.join(ROOT, 'node_modules', 'cloudflare', 'resources');
const OUT_DIR = path.join(ROOT, 'coverage');
const OUT_PATH = path.join(OUT_DIR, 'sdk-index.generated.json');

if (!fs.existsSync(SDK_ROOT)) {
  console.error(`SDK resources directory not found: ${SDK_ROOT}`);
  console.error('Did you run `npm install`?');
  process.exit(1);
}

/**
 * Recursively walk a directory and yield every `.js` file (skipping `.d.ts`,
 * `.mjs`, `.map`, and `_*` private modules).
 */
function* walkJs(dir) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('_')) continue;
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      yield* walkJs(full);
    } else if (ent.isFile() && ent.name.endsWith('.js') && !ent.name.endsWith('.d.ts')) {
      yield full;
    }
  }
}

/**
 * For one SDK source file, extract every method that issues an HTTP call.
 *
 * SDK pattern (generated by Stainless from the OpenAPI spec):
 *   methodName(args) {
 *     ...
 *     return this._client.<verb>(`<url_template>`, ...);
 *   }
 *
 * We find each method head, then look ahead inside the same function body for
 * a `this._client.<verb>(\`...\``) call.
 */
function extractFromFile(filePath) {
  const src = fs.readFileSync(filePath, 'utf8');
  const rel = path.relative(SDK_ROOT, filePath).replace(/\.js$/, '');
  // Convert "dns/records" or "zones/settings/index" → resource dotted path.
  // "index" segments collapse (e.g. "zones/index" → "zones").
  const segments = rel.split(path.sep).filter(s => s !== 'index');
  const resourcePath = segments.join('.');

  const results = [];

  // Find class definitions and the methods inside them. We want methods that
  // contain a `this._client.<verb>(\`<template>\`, ...)` call.
  // A simple regex over the whole file body catches every such call regardless
  // of which method it's in, but we also want to attach the *method name* so we
  // can later map "create" / "update" / "edit" / "delete" to the right endpoint.
  //
  // Method header pattern: `methodName(args) {` (Stainless never uses arrow
  // methods at the top level of a class body in these generated files).
  const methodHeaderRe = /^\s{4}([a-zA-Z_$][a-zA-Z0-9_$]*)\s*\([^)]*\)\s*\{$/gm;
  // For each method header, slice from its body start to the matching close
  // brace. Counting braces is overkill here — instead, slice to the next
  // method header (or end of file) and search that slice.
  const headers = [...src.matchAll(methodHeaderRe)];
  for (let i = 0; i < headers.length; i++) {
    const methodName = headers[i][1];
    if (methodName === 'constructor') continue;
    const bodyStart = headers[i].index + headers[i][0].length;
    const bodyEnd = i + 1 < headers.length ? headers[i + 1].index : src.length;
    const body = src.slice(bodyStart, bodyEnd);

    // Look for `this._client.<verb>(\`<url>\`, ...)` — verb is one of
    // get/post/put/patch/delete. Templates use backticks so we capture them.
    // Some methods construct the URL into a variable first; for those we fall
    // back to scanning for a backtick literal earlier in the body.
    const callRe = /this\._client\.(get|post|put|patch|delete)\(\s*`([^`]+)`/g;
    let m;
    while ((m = callRe.exec(body)) !== null) {
      const httpMethod = m[1].toUpperCase();
      const urlTemplate = m[2];
      // Normalize SDK URL templates (`${zoneId}`) to OpenAPI templates
      // (`{zone_id}`). The SDK uses the JS variable name (camelCase) while
      // OpenAPI uses snake_case. We keep the original name on the entry for
      // human readability and also emit a `path_shape` field that strips all
      // template names and keeps only positional placeholders, so the
      // cross-reference in coverage-report.mjs can match by shape.
      const rawPath = urlTemplate
        .replace(/\$\{([a-zA-Z_$][a-zA-Z0-9_$]*)\}/g, (_, name) => `{${name}}`)
        .replace(/\$\{[^}]*\}/g, '{param}');
      // SDK uses a synthetic dual-scope template for endpoints that work at both
      // account and zone level: `/{accountOrZone}/{accountOrZoneId}/...`.
      // OpenAPI lists these as two distinct paths (`/accounts/{account_id}/...`
      // and `/zones/{zone_id}/...`). Expand the SDK entry into both so the
      // cross-reference works.
      const expandedPaths = rawPath.includes('{accountOrZone}/{accountOrZoneId}')
        ? [
            rawPath.replace('{accountOrZone}/{accountOrZoneId}', 'accounts/{account_id}'),
            rawPath.replace('{accountOrZone}/{accountOrZoneId}', 'zones/{zone_id}'),
          ]
        : [rawPath];
      for (const p of expandedPaths) {
        // Positional shape: replace any `{name}` placeholder with `{}` so the
        // cross-reference can match regardless of parameter naming.
        // `/zones/{zoneId}/dns_records/{recordId}` and
        // `/zones/{zone_id}/dns_records/{dns_record_id}` both become
        // `/zones/{}/dns_records/{}`.
        const pathShape = p.replace(/\{[^}]+\}/g, '{}');
        results.push({
          sdk_path: resourcePath,
          method: methodName,
          http_method: httpMethod,
          path: p,
          path_shape: pathShape,
          dual_scope: expandedPaths.length > 1,
        });
      }
    }
  }

  return results;
}

const all = [];
let fileCount = 0;
for (const file of walkJs(SDK_ROOT)) {
  fileCount++;
  for (const entry of extractFromFile(file)) all.push(entry);
}

// Build derived indices:
//   - by_path_method:  "POST /zones/{zone_id}/dns_records" → [entries...]      (literal SDK names)
//   - by_shape_method: "POST /zones/{}/dns_records"        → [entries...]      (positional, for OpenAPI cross-ref)
//   - by_sdk_path:     "dns.records"                       → [entries...]
const byPathMethod = {};
const byShapeMethod = {};
const bySdkPath = {};
for (const e of all) {
  const pathKey = `${e.http_method} ${e.path}`;
  const shapeKey = `${e.http_method} ${e.path_shape}`;
  (byPathMethod[pathKey] ||= []).push(e);
  (byShapeMethod[shapeKey] ||= []).push(e);
  (bySdkPath[e.sdk_path] ||= []).push(e);
}

// Method-counts summary for sanity.
const httpCounts = {};
for (const e of all) httpCounts[e.http_method] = (httpCounts[e.http_method] || 0) + 1;

const output = {
  generated_at: new Date().toISOString(),
  sdk_files_scanned: fileCount,
  total_entries: all.length,
  http_counts: httpCounts,
  entries: all,
  by_path_method: byPathMethod,
  by_shape_method: byShapeMethod,
  by_sdk_path: bySdkPath,
};

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_PATH, JSON.stringify(output, null, 2));

// Human summary
console.log(`✓ Scanned ${fileCount} SDK files`);
console.log(`✓ Extracted ${all.length} HTTP-issuing methods`);
for (const [m, c] of Object.entries(httpCounts).sort()) {
  console.log(`    ${m.padEnd(7)} ${c}`);
}
console.log(`✓ Wrote ${OUT_PATH}`);
